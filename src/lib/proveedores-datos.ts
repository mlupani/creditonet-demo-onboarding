const sinGravar = (): GravadoIva => ({ base: 0, iva: 0 });

// Comprobante de ejemplo: un único tramo gravado al 21 % (o ninguno).
function comprobante(
  n: number,
  c: Pick<Comprobante, "proveedorId" | "tipoId" | "fechaComprobante" | "prefijo" | "numero" | "estado" | "cargadoPor" | "fechaCarga"> &
    Partial<Comprobante> & { base21?: number; noGravado?: number }
): Comprobante {
  const { base21 = 0, noGravado = 0, ...resto } = c;
  const iva = Math.round(base21 * 0.21 * 100) / 100;
  return {
    id: `CMP-${String(n).padStart(4, "0")}`,
    exento: 0,
    percepcionIva: 0,
    percepcionesIibb: [],
    percepcionesMunicipales: [],
    observaciones: "",
    noGravado,
    subtotalGravado: base21,
    gravados: { "10.5": sinGravar(), "21": { base: base21, iva }, "27": sinGravar() },
    total: noGravado + base21 + iva,
    ...resto,
  };
}

